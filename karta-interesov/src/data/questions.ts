/** Convert raw score (−12..+12) to 0–100 display scale */
export function toDisplay(raw: number): number {
  return Math.round(((raw + 12) / 24) * 100);
}

export function calculateResults(answers: Record<number, number>): Record<number, number> {
  const scores: Record<number, number> = {};
  CATEGORIES.forEach(cat => { scores[cat.id] = 0; });
  QUESTIONS.forEach(q => {
    if (answers[q.id] !== undefined) {
      scores[q.categoryId] = (scores[q.categoryId] || 0) + answers[q.id];
    }
  });
  return scores;
}
