-- Supabase PostgreSQL schema for Karta Interesov
-- Migrated from MySQL structure in backend/database/migrations
-- Converted for Supabase Auth + PostgreSQL.

BEGIN;

-- Required for text/email handling and unique profile insertion.
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 1) Profiles linked to Supabase Auth users.
CREATE TABLE IF NOT EXISTS public.profiles (
    id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    email text NOT NULL UNIQUE,
    display_name text NULL,
    region_id smallint NULL REFERENCES public.regions(id),
    age smallint NULL,
    failed_logins smallint NOT NULL DEFAULT 0,
    locked_until timestamptz NULL,
    role text NOT NULL DEFAULT 'user' CHECK (role IN ('user', 'admin')),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT chk_profiles_age CHECK (age IS NULL OR (age >= 10 AND age <= 100))
);

CREATE INDEX IF NOT EXISTS idx_profiles_region_id
    ON public.profiles (region_id);

CREATE INDEX IF NOT EXISTS idx_profiles_role
    ON public.profiles (role);

-- Automatic profile creation for every Supabase auth user.
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    INSERT INTO public.profiles (id, email, display_name, created_at, updated_at)
    VALUES (
        NEW.id,
        NEW.email,
        COALESCE(NEW.raw_user_meta_data ->> 'full_name', split_part(NEW.email, '@', 1)),
        NOW(),
        NOW()
    )
    ON CONFLICT (id) DO NOTHING;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW
    EXECUTE FUNCTION public.handle_new_user();

-- 2) Regions.
CREATE TABLE IF NOT EXISTS public.regions (
    id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code text NOT NULL UNIQUE,
    name text NOT NULL UNIQUE,
    kind text NOT NULL CHECK (kind IN ('region', 'city')),
    kato_code text NULL UNIQUE,
    sort_order smallint NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_regions_code
    ON public.regions (code);

CREATE UNIQUE INDEX IF NOT EXISTS uq_regions_name
    ON public.regions (name);

CREATE UNIQUE INDEX IF NOT EXISTS uq_regions_kato
    ON public.regions (kato_code)
    WHERE kato_code IS NOT NULL;

-- 3) Categories.
CREATE TABLE IF NOT EXISTS public.categories (
    id smallint PRIMARY KEY,
    name text NOT NULL UNIQUE,
    description text NOT NULL,
    color char(7) NOT NULL CHECK (color ~ '^#[0-9A-Fa-f]{6}$'),
    icon text NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_categories_name
    ON public.categories (name);

-- 4) Questions.
CREATE TABLE IF NOT EXISTS public.questions (
    id smallint PRIMARY KEY,
    category_id smallint NOT NULL REFERENCES public.categories(id),
    text text NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_questions_category
    ON public.questions (category_id);

-- 5) Test attempts.
CREATE TABLE IF NOT EXISTS public.test_attempts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    client_attempt_id text NOT NULL,
    test_version text NOT NULL,
    region_id smallint NULL REFERENCES public.regions(id),
    status text NOT NULL DEFAULT 'in_progress' CHECK (status IN ('in_progress', 'completed')),
    current_round smallint NOT NULL DEFAULT 1,
    current_question_id smallint NULL REFERENCES public.questions(id),
    question_opened_at timestamptz NULL,
    started_at timestamptz NOT NULL DEFAULT now(),
    completed_at timestamptz NULL,
    answered_count smallint NULL,
    calculated_at timestamptz NULL,
    CONSTRAINT uq_attempts_user_client UNIQUE (user_id, client_attempt_id),
    CONSTRAINT chk_attempts_completed CHECK (status IN ('in_progress') OR completed_at IS NOT NULL),
    CONSTRAINT chk_attempts_open_question CHECK ((current_question_id IS NULL) = (question_opened_at IS NULL))
);

CREATE INDEX IF NOT EXISTS idx_attempts_status
    ON public.test_attempts (status);

CREATE INDEX IF NOT EXISTS idx_attempts_completed
    ON public.test_attempts (completed_at);

CREATE INDEX IF NOT EXISTS idx_attempts_region_completed
    ON public.test_attempts (region_id, completed_at);

-- 6) Answers.
CREATE TABLE IF NOT EXISTS public.answers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id bigint NOT NULL REFERENCES public.test_attempts(id) ON DELETE CASCADE,
    question_id smallint NOT NULL REFERENCES public.questions(id),
    status text NOT NULL CHECK (status IN ('answered', 'skipped')),
    value smallint NULL,
    last_round smallint NOT NULL,
    skip_count smallint NOT NULL DEFAULT 0,
    shown_at timestamptz NOT NULL,
    resolved_at timestamptz NOT NULL,
    CONSTRAINT uq_answers_attempt_question UNIQUE (attempt_id, question_id),
    CONSTRAINT chk_answers_value CHECK (
        (status = 'answered' AND value BETWEEN -2 AND 2)
        OR (status = 'skipped' AND value IS NULL)
    )
);

CREATE INDEX IF NOT EXISTS idx_answers_question
    ON public.answers (question_id);

CREATE INDEX IF NOT EXISTS idx_answers_attempt_status
    ON public.answers (attempt_id, status);

-- 7) Attempt results.
CREATE TABLE IF NOT EXISTS public.attempt_results (
    attempt_id bigint NOT NULL REFERENCES public.test_attempts(id) ON DELETE CASCADE,
    category_id smallint NOT NULL REFERENCES public.categories(id),
    raw_score smallint NOT NULL,
    display_score smallint NOT NULL CHECK (display_score BETWEEN 0 AND 100),
    rank_position smallint NOT NULL CHECK (rank_position > 0),
    PRIMARY KEY (attempt_id, category_id),
    CONSTRAINT uq_results_attempt_rank UNIQUE (attempt_id, rank_position),
    CONSTRAINT chk_results_raw_score CHECK (raw_score BETWEEN -12 AND 12)
);

CREATE INDEX IF NOT EXISTS idx_results_category_rank
    ON public.attempt_results (category_id, rank_position);

-- 8) Admin accounts and audit logs.
CREATE TABLE IF NOT EXISTS public.admin_users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username text NOT NULL UNIQUE,
    password_hash text NOT NULL,
    is_active boolean NOT NULL DEFAULT true,
    failed_logins smallint NOT NULL DEFAULT 0,
    locked_until timestamptz NULL,
    token_hash text NULL UNIQUE,
    token_expires_at timestamptz NULL,
    last_login_at timestamptz NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT chk_admin_users_username CHECK (length(trim(username)) > 0)
);

CREATE INDEX IF NOT EXISTS idx_admin_users_token
    ON public.admin_users (token_hash);

CREATE TABLE IF NOT EXISTS public.admin_audit_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_user_id bigint NULL REFERENCES public.admin_users(id) ON DELETE SET NULL,
    username_attempted text NULL,
    action text NOT NULL,
    entity_type text NULL,
    entity_id text NULL,
    details jsonb NULL,
    ip_address text NOT NULL,
    user_agent text NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_audit_admin_created
    ON public.admin_audit_logs (admin_user_id, created_at);

CREATE INDEX IF NOT EXISTS idx_audit_action_created
    ON public.admin_audit_logs (action, created_at);

COMMIT;
