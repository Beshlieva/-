-- Профиль пользователя создаётся триггером сразу при регистрации в Supabase Auth — из данных,
-- переданных в supabase.auth.signUp({ options: { data } }). Так профиль заполняется полностью,
-- даже если включено подтверждение email и у браузера ещё нет сессии (клиент в profiles не пишет).
CREATE OR REPLACE FUNCTION public.profile_values_from_meta(p_email text, p_meta jsonb)
RETURNS TABLE (display_name text, age smallint, region_id smallint)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_meta jsonb := COALESCE(p_meta, '{}'::jsonb);
    v_name text;
    v_age_text text := btrim(COALESCE(v_meta ->> 'age', ''));
BEGIN
    v_name := NULLIF(btrim(COALESCE(v_meta ->> 'full_name', '')), '');
    IF v_name IS NULL THEN
        v_name := NULLIF(btrim(concat_ws(' ', NULLIF(btrim(v_meta ->> 'first_name'), ''), NULLIF(btrim(v_meta ->> 'last_name'), ''))), '');
    END IF;
    display_name := COALESCE(left(v_name, 120), NULLIF(split_part(COALESCE(p_email, ''), '@', 1), ''));

    age := NULL;
    IF v_age_text ~ '^[0-9]{1,3}$' AND v_age_text::int BETWEEN 10 AND 100 THEN
        age := v_age_text::smallint;
    END IF;

    SELECT r.id INTO region_id FROM public.regions r WHERE r.code = v_meta ->> 'region_code';
    RETURN NEXT;
END;
$$;

CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v record;
BEGIN
    SELECT * INTO v FROM public.profile_values_from_meta(NEW.email, NEW.raw_user_meta_data);

    INSERT INTO public.profiles (id, email, display_name, age, region_id, created_at, updated_at)
    VALUES (NEW.id, COALESCE(NEW.email, NEW.id::text || '@unknown'), v.display_name, v.age, v.region_id, now(), now())
    ON CONFLICT (id) DO UPDATE
       SET email        = EXCLUDED.email,
           display_name = COALESCE(EXCLUDED.display_name, public.profiles.display_name),
           age          = COALESCE(EXCLUDED.age, public.profiles.age),
           region_id    = COALESCE(EXCLUDED.region_id, public.profiles.region_id),
           updated_at   = now();

    RETURN NEW;
END;
$$;

-- При смене email в Supabase Auth обновляем его и в профиле.
CREATE OR REPLACE FUNCTION public.handle_user_email_change()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    IF NEW.email IS DISTINCT FROM OLD.email AND NEW.email IS NOT NULL THEN
        UPDATE public.profiles SET email = NEW.email, updated_at = now() WHERE id = NEW.id;
    END IF;
    RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION public.profile_values_from_meta(text, jsonb) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.handle_new_user() FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.handle_user_email_change() FROM PUBLIC, anon, authenticated;

-- ============================================================
-- 5) Triggers
-- ============================================================

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW
    EXECUTE FUNCTION public.handle_new_user();

DROP TRIGGER IF EXISTS on_auth_user_email_changed ON auth.users;
CREATE TRIGGER on_auth_user_email_changed
    AFTER UPDATE OF email ON auth.users
    FOR EACH ROW
    EXECUTE FUNCTION public.handle_user_email_change();

-- ============================================================
-- 6) Дозаполнение профилей, созданных до исправления триггера
--    (у них не сохранялись возраст и регион). Безопасно запускать повторно.
-- ============================================================

INSERT INTO public.profiles (id, email, display_name, age, region_id)
SELECT u.id, COALESCE(u.email, u.id::text || '@unknown'), v.display_name, v.age, v.region_id
  FROM auth.users u
 CROSS JOIN LATERAL public.profile_values_from_meta(u.email, u.raw_user_meta_data) v
 WHERE NOT EXISTS (SELECT 1 FROM public.profiles p WHERE p.id = u.id)
ON CONFLICT (id) DO NOTHING;

UPDATE public.profiles p
   SET age        = COALESCE(p.age, v.age),
       region_id  = COALESCE(p.region_id, v.region_id),
       display_name = COALESCE(NULLIF(p.display_name, ''), v.display_name),
       updated_at = now()
  FROM auth.users u
 CROSS JOIN LATERAL public.profile_values_from_meta(u.email, u.raw_user_meta_data) v
 WHERE u.id = p.id
   AND (p.age IS NULL OR p.region_id IS NULL);

COMMIT;
